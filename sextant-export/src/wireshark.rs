    use sextant_ir::{Bytes, Confidence, EnumVariant, Metadata};

    /// Build a little-endian format from a list of root fields.
    fn format_of(fields: Vec<Field>, enums: BTreeMap<String, EnumDef>) -> Format {
        Format {
            name: "t".to_owned(),
            endianness: Endianness::Little,
            root: Structure::new(fields),
            enums,
            metadata: Metadata::default(),
        }
    }

    #[test]
    fn signed_field_uses_a_signed_reader() {
        let field = Field::new(
            Kind::Integer {
                width: 2,
                signed: Signedness::Signed,
                endianness: None,
            },
            Confidence::CERTAIN,
        )
        .with_name("delta");
        let lua = export(&format_of(vec![field], BTreeMap::new()));
        // A signed value is read with a signed reader so it keeps its sign.
        assert!(lua.contains(":le_int()"), "got:\n{lua}");
        assert!(lua.contains("ProtoField.int16(\"t.delta\""), "got:\n{lua}");
    }

    #[test]
    fn delimited_field_scans_for_its_terminator() {
        let field = Field::new(Kind::Bytes, Confidence::CERTAIN)
            .with_name("name")
            .with_size(SizeRule::Delimited {
                terminator: Bytes::new(vec![0x00]),
                include_terminator: false,
            });
        let lua = export(&format_of(vec![field], BTreeMap::new()));
        // The dissector scans for the terminator rather than reading to end.
        assert!(lua.contains(":bytes():tohex() == \"00\""), "got:\n{lua}");
    }

    #[test]
    fn protocol_metadata_binds_the_dissector_to_its_port() {
        // A format inferred from a capture records its transport and port, so the
        // exporter emits an active DissectorTable registration (Step 11).
        let mut format = format_of(
            vec![
                Field::new(Kind::Bytes, Confidence::CERTAIN)
                    .with_name("payload")
                    .with_size(SizeRule::ToEnd),
            ],
            BTreeMap::new(),
        );
        format
            .metadata
            .extra
            .insert("protocol.transport".to_owned(), "tcp".to_owned());
        format
            .metadata
            .extra
            .insert("protocol.port".to_owned(), "502".to_owned());
        let lua = export(&format);
        assert!(
            lua.contains("DissectorTable.get(\"tcp.port\"):add(502, proto_t)"),
            "got:\n{lua}"
        );
        // The binding is active, not the commented placeholder.
        assert!(
            !lua.contains("-- DissectorTable.get(\"udp.port\")"),
            "got:\n{lua}"
        );
    }

    #[test]
    fn malicious_array_element_name_cannot_inject_lua() {
        // An array element's display label is taken from its raw name, which may
        // come from a hostile model response or a crafted sample. A name carrying
        // a double quote and Lua code must be escaped into the label literal, not
        // injected into the dissector the user loads in Wireshark.
        let element = Field::new(Kind::Bytes, Confidence::CERTAIN)
            .with_name("x\") os.execute(\"id\")--")
            .with_size(SizeRule::Fixed { bytes: 1 });
        let array = Field::new(
            Kind::Array {
                element: Box::new(element),
                count: CountRule::Fixed { count: 1 },
            },
            Confidence::CERTAIN,
        )
        .with_name("items");
        let lua = export(&format_of(vec![array], BTreeMap::new()));
        // The injected quote is escaped, so the label literal stays closed.
        assert!(
            lua.contains("x\\\") os.execute"),
            "name not escaped:\n{lua}"
        );
        // The raw breakout sequence (an unescaped quote then Lua) never appears.
        assert!(
            !lua.contains("\"x\") os.execute"),
            "lua injection in dissector:\n{lua}"
        );
    }

    #[test]
    fn malicious_enum_variant_name_is_escaped() {
        // Enum variant names flow into a Lua value-string table. A newline or
        // quote in a variant name must be escaped so the table stays well formed.
        let mut enums = BTreeMap::new();
        enums.insert(
            "kind".to_owned(),
            EnumDef {
                width: Some(1),
                variants: vec![EnumVariant {
                    value: 1,
                    name: "a\"]=os.execute(\"id\")\n--".to_owned(),
                    description: None,
                }],
            },
        );
        let field = Field::new(
            Kind::Enum {
                enum_ref: "kind".to_owned(),
                width: 1,
                endianness: None,
            },
            Confidence::CERTAIN,
        )
        .with_name("kind");
        let lua = export(&format_of(vec![field], enums));
        // No raw newline survives inside the generated source line.
        assert!(
            !lua.contains("os.execute(\"id\")\n"),
            "unescaped newline in lua:\n{lua}"
        );
        assert!(lua.contains("\\n"), "newline not escaped:\n{lua}");
    }

    #[test]
    fn enum_field_emits_a_value_string_table() {
        let mut enums = BTreeMap::new();
        enums.insert(
            "kind".to_owned(),
            EnumDef {
                width: Some(1),
                variants: vec![
                    EnumVariant {
                        value: 1,
                        name: "alpha".to_owned(),
                        description: None,
                    },
                    EnumVariant {
                        value: 2,
                        name: "beta".to_owned(),
                        description: None,
                    },
                ],
            },
        );
        let field = Field::new(
            Kind::Enum {
                enum_ref: "kind".to_owned(),
                width: 1,
                endianness: None,
            },
            Confidence::CERTAIN,
        )
        .with_name("kind");
        let lua = export(&format_of(vec![field], enums));
        assert!(lua.contains("[1]=\"alpha\""), "got:\n{lua}");
        assert!(lua.contains("[2]=\"beta\""), "got:\n{lua}");
        assert!(lua.contains("base.DEC"), "got:\n{lua}");
    }
